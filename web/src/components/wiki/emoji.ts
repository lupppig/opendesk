export function searchEmoji(q: string): string[] {
  const words = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const out: string[] = [];
  for (const g of EMOJI) for (const [e, names] of g.emoji) if (words.every((w) => names.split(" ").some((n) => n.startsWith(w)))) out.push(e);
  return out;
}
