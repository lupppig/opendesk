// Package jobs defines every background job's arguments. Areas enqueue by args type and
// the owning area registers the worker (see internal/app). River runs them on Postgres.
package jobs

import "github.com/google/uuid"

// Queues.
const (
	QueueDefault  = "default"
	QueueEmail    = "email"
	QueueWebhooks = "webhooks"
)

// SendMessageArgs sends an outbound email reply (messages.delivery_status = pending). Owner: email.
type SendMessageArgs struct {
	WorkspaceID uuid.UUID `json:"workspace_id"`
	MessageID   uuid.UUID `json:"message_id"`
}

func (SendMessageArgs) Kind() string { return "email.send_message" }

// SendTicketEmailArgs sends a non-message email from the ticket's mailbox to its contact
// (auto-reply, CSAT request). Owner: email.
type SendTicketEmailArgs struct {
	WorkspaceID uuid.UUID `json:"workspace_id"`
	TicketID    uuid.UUID `json:"ticket_id"`
	Subject     string    `json:"subject"`
	HTML        string    `json:"html"`
	Text        string    `json:"text"`
	// AutoGenerated marks the mail Auto-Submitted so other autoresponders ignore it.
	AutoGenerated bool `json:"auto_generated"`
	// Template marks Subject and HTML as templates filled when the email is sent
	// (contracts/templates.md); SurveyURL fills {{ survey }} with score links to it plus
	// the score.
	Template  bool   `json:"template,omitempty"`
	SurveyURL string `json:"survey_url,omitempty"`
}

func (SendTicketEmailArgs) Kind() string { return "email.send_ticket_email" }

