package email

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"io"
	"mime"
	"mime/multipart"
	"mime/quotedprintable"
	"net/mail"
	"net/textproto"
	"strings"
	"time"
)

type outAttachment struct {
	Filename    string
	ContentType string
	Data        []byte
	ContentID   string // set for inline images referenced as cid: in HTML
}

// outMessage is an outbound email before encoding.
type outMessage struct {
	From          mail.Address
	ReplyTo       *mail.Address
	To, Cc, Bcc   []string
	Subject       string
	MessageID     string
	InReplyTo     string
	References    []string
	HTML, Text    string
	Attachments   []outAttachment
	AutoGenerated bool
	Date          time.Time
	// Loop is the sending mailbox's loop token (loopToken), written to X-Loop so the
	// workspace recognizes its own mail when it comes back.
	Loop string
	// GmailThread is the Gmail thread the message joins (providerThread), not a header.
	GmailThread string
	// sent is where deliver's message lives at the provider, when it can tell.
	sent *providerRef
}

// loopHeader carries the sending mailbox's loop token, on every message we send.
const loopHeader = "X-Loop"

// headerSafe drops CR, LF and other controls so no value can inject a header.
func headerSafe(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '\t' {
			return ' '
		}
		if r < 0x20 || r == 0x7f {
			return -1
		}
		return r
	}, s)
}

func addrList(list []string) string {
	out := make([]string, 0, len(list))
	for _, a := range list {
		if a = headerSafe(strings.TrimSpace(a)); a != "" {
			out = append(out, (&mail.Address{Address: a}).String())
		}
	}
	return strings.Join(out, ", ")
}

func fmtAddress(a mail.Address) string {
	a.Name, a.Address = headerSafe(a.Name), headerSafe(a.Address)
	return a.String()
}

// foldIDs folds a list of message ids over several header lines.
func foldIDs(ids []string) string {
	var b strings.Builder
	line := 0
	for i, id := range ids {
		id = headerSafe(id)
		if i > 0 {
			if line+len(id) > 70 {
				b.WriteString("\r\n ")
				line = 1
			} else {
				b.WriteByte(' ')
				line++
			}
		}
		b.WriteString(id)
		line += len(id)
	}
	return b.String()
}

// buildMIME encodes m. includeBcc keeps a Bcc header for API transports that read
// recipients from the message (Gmail, Graph); SMTP passes Bcc in the envelope only.
func buildMIME(m *outMessage, includeBcc bool) ([]byte, error) {
	var buf bytes.Buffer
	h := func(k, v string) {
		if v != "" {
			buf.WriteString(k + ": " + v + "\r\n")
		}
	}
	if m.Date.IsZero() {
		m.Date = time.Now()
	}
	h("From", fmtAddress(m.From))
	if m.ReplyTo != nil {
		h("Reply-To", fmtAddress(*m.ReplyTo))
	}
	h("To", addrList(m.To))
	h("Cc", addrList(m.Cc))
	if includeBcc {
		h("Bcc", addrList(m.Bcc))
	}
	h("Subject", mime.QEncoding.Encode("utf-8", headerSafe(m.Subject)))
	h("Date", m.Date.UTC().Format(time.RFC1123Z))
	h("Message-ID", headerSafe(m.MessageID))
	h("In-Reply-To", headerSafe(m.InReplyTo))
	if len(m.References) > 0 {
		h("References", foldIDs(m.References))
	}
	h("MIME-Version", "1.0")
	if m.Loop != "" {
		h(loopHeader, headerSafe(m.Loop))
	}
	if m.AutoGenerated {
		h("Auto-Submitted", "auto-generated")
		h("X-Auto-Response-Suppress", "All")
	}

	var inline, files []outAttachment
	for _, a := range m.Attachments {
		if a.ContentID != "" {
			inline = append(inline, a)
		} else {
			files = append(files, a)
		}
	}

	// alternative: text + html
	alt := func(w io.Writer) (string, error) {
		mw := multipart.NewWriter(w)
		for _, p := range []struct{ ct, body string }{{"text/plain; charset=utf-8", m.Text}, {"text/html; charset=utf-8", m.HTML}} {
			pw, err := mw.CreatePart(textproto.MIMEHeader{"Content-Type": {p.ct}, "Content-Transfer-Encoding": {"quoted-printable"}})
			if err != nil {
				return "", err
			}
			qp := quotedprintable.NewWriter(pw)
			if _, err := qp.Write([]byte(strings.ReplaceAll(strings.ReplaceAll(p.body, "\r\n", "\n"), "\n", "\r\n"))); err != nil {
				return "", err
			}
			if err := qp.Close(); err != nil {
				return "", err
			}
		}
		return mw.Boundary(), mw.Close()
	}
	// related: alternative + inline images
	related := func(w io.Writer) (string, error) {
		mw := multipart.NewWriter(w)
		var inner bytes.Buffer
		b, err := alt(&inner)
		if err != nil {
			return "", err
		}
		pw, err := mw.CreatePart(textproto.MIMEHeader{"Content-Type": {`multipart/alternative; boundary="` + b + `"`}})
		if err != nil {
			return "", err
		}
		if _, err := pw.Write(inner.Bytes()); err != nil {
			return "", err
		}
		for _, a := range inline {
			if err := writeAttachment(mw, a, true); err != nil {
				return "", err
			}
		}
		return mw.Boundary(), mw.Close()
	}

	var body bytes.Buffer
	var ct string
	switch {
	case len(files) == 0 && len(inline) == 0:
		b, err := alt(&body)
		if err != nil {
			return nil, err
		}
		ct = `multipart/alternative; boundary="` + b + `"`
	case len(files) == 0:
		b, err := related(&body)
		if err != nil {
			return nil, err
		}
		ct = `multipart/related; boundary="` + b + `"`
	default:
		mw := multipart.NewWriter(&body)
		var inner bytes.Buffer
		innerCT := ""
		if len(inline) > 0 {
			b, err := related(&inner)
			if err != nil {
				return nil, err
			}
			innerCT = `multipart/related; boundary="` + b + `"`
		} else {
			b, err := alt(&inner)
			if err != nil {
				return nil, err
			}
			innerCT = `multipart/alternative; boundary="` + b + `"`
		}
		pw, err := mw.CreatePart(textproto.MIMEHeader{"Content-Type": {innerCT}})
		if err != nil {
			return nil, err
		}
		if _, err := pw.Write(inner.Bytes()); err != nil {
			return nil, err
		}
		for _, a := range files {
			if err := writeAttachment(mw, a, false); err != nil {
				return nil, err
			}
		}
		if err := mw.Close(); err != nil {
			return nil, err
		}
		ct = `multipart/mixed; boundary="` + mw.Boundary() + `"`
	}
	h("Content-Type", ct)
	buf.WriteString("\r\n")
	buf.Write(body.Bytes())
	return buf.Bytes(), nil
}

func writeAttachment(mw *multipart.Writer, a outAttachment, inline bool) error {
	ct := a.ContentType
	if _, _, err := mime.ParseMediaType(ct); err != nil || ct == "" {
		ct = "application/octet-stream"
	}
	name := headerSafe(a.Filename)
	disp := "attachment"
	if inline {
		disp = "inline"
	}
	hdr := textproto.MIMEHeader{
		"Content-Type":              {mime.FormatMediaType(ct, map[string]string{"name": name})},
		"Content-Disposition":       {mime.FormatMediaType(disp, map[string]string{"filename": name})},
		"Content-Transfer-Encoding": {"base64"},
	}
	if hdr.Get("Content-Type") == "" {
		hdr.Set("Content-Type", ct)
	}
	if hdr.Get("Content-Disposition") == "" {
		hdr.Set("Content-Disposition", disp)
	}
	if a.ContentID != "" {
		hdr.Set("Content-ID", "<"+headerSafe(a.ContentID)+">")
	}
	pw, err := mw.CreatePart(hdr)
	if err != nil {
		return err
	}
	enc := base64.StdEncoding.EncodeToString(a.Data)
	for i := 0; i < len(enc); i += 76 {
		end := min(i+76, len(enc))
		if _, err := fmt.Fprintf(pw, "%s\r\n", enc[i:end]); err != nil {
			return err
		}
	}
	return nil
}
