type recordingMailer struct {
	mu   sync.Mutex
	sent []mailer.Mail
}

func (m *recordingMailer) Send(_ context.Context, mail mailer.Mail) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.sent = append(m.sent, mail)
	return nil
}

// sendReply sends an agent reply and returns it as the customer gets it.
func (w *world) sendReply(t *testing.T, ticketID [16]byte, body string) *enmime.Envelope {
	t.Helper()
	var sent [][]byte
	prev := w.s.rawSend
	w.s.rawSend = func(_ context.Context, _ string, _ []string, raw []byte) error { sent = append(sent, raw); return nil }
	defer func() { w.s.rawSend = prev }()
	mid := w.agentReply(ticketID, body, "")
	if err := w.s.sendMessage(w.ctx, w.wid, mid, false); err != nil {
		t.Fatal(err)
	}
	if len(sent) != 1 {
		t.Fatalf("sent %d", len(sent))
	}
	env, err := enmime.ReadEnvelope(bytes.NewReader(sent[0]))
	if err != nil {
		t.Fatal(err)
	}
	env.Text = strings.ReplaceAll(env.Text, "\r\n", "\n")
	return env
}

func TestReplyLayoutHistoryAndPersonalSignature(t *testing.T) {
	w := newWorld(t)
	m := w.mailbox(InboundForwarding, OutboundSystem, nil)
	mustExec(t, w.d, `UPDATE members SET title = 'Support lead', phone = '+1 555 0100', signature_html = '<p>{{ agent.first_name }}, {{ agent.title }}</p>'
		WHERE workspace_id = $1 AND user_id = $2`, w.wid, w.uid)
	id := w.receive(m, rawMail("Carla Diaz <"+customer()+">", m.Email, "Refund please", ""))
	tk := w.ticket(w.messageFor(id).TicketID)

	// No team or address signature: the sender's own, filled; the customer's message quoted.
	env := w.sendReply(t, tk.ID, "On it")
	if !strings.Contains(env.HTML, "<p>Anna, Support lead</p>") || !strings.Contains(env.Text, "-- \nAnna, Support lead") {
		t.Errorf("personal signature: %s", env.HTML)
	}
	if !strings.Contains(env.HTML, "Carla Diaz wrote:") || !strings.Contains(env.Text, "Carla Diaz wrote:\n>") {
		t.Errorf("history: %s\n%s", env.HTML, env.Text)
	}

	// An address signature wins and can place the personal one; the branded layout with
	// a footer and no history.
	mustExec(t, w.d, `UPDATE mailboxes SET signature_html = '<div>{{ agent.signature }}</div><p>Acme support{% if agent.phone %}, call {{ agent.phone }}{% endif %}</p>' WHERE id = $1`, m.ID)
	mustExec(t, w.d, `INSERT INTO email_templates (workspace_id, brand_id, kind, options) VALUES ($1, $2, 'layout',
		'{"mode":"simple","style":"branded","logo":true,"accent":"#2563EB","font":"serif","footer_html":"<p>{{ brand.name }} Ltd</p>","history":"none"}')`, w.wid, w.brand)
	env = w.sendReply(t, tk.ID, "Done")
	for _, want := range []string{"<p>Anna, Support lead</p>", "Acme support, call +1 555 0100", "Acme Ltd", "border-top:3px solid #2563EB", "Georgia"} {
		if !strings.Contains(env.HTML, want) {
			t.Errorf("missing %q in %s", want, env.HTML)
		}
	}
	if strings.Contains(env.HTML, "wrote:") {
		t.Errorf("history quoted with history none: %s", env.HTML)
	}

	// A custom layout puts the message where it says.
	mustExec(t, w.d, `UPDATE email_templates SET body_html = '<div class="x" style="padding: 8px">[{{ content }}]</div>', options = '{"mode":"custom","history":"all"}'
		WHERE workspace_id = $1`, w.wid)
	env = w.sendReply(t, tk.ID, "Custom")
	if !strings.Contains(env.HTML, `[<p>Custom</p>]`) {
		t.Errorf("custom layout: %s", env.HTML)
	}
}

func TestCSATEmailAsSent(t *testing.T) {
	w := newWorld(t)
	m := w.mailbox(InboundForwarding, OutboundSystem, nil)
	billing := w.team("Billing", false, "")
	mustExec(t, w.d, `UPDATE brands SET color = '#2563EB' WHERE id = $1`, w.brand)
	id := w.receive(m, rawMail("Carla Diaz <"+customer()+">", m.Email, "Refund", ""))
	tk := w.ticket(w.messageFor(id).TicketID)
	mustExec(t, w.d, `UPDATE tickets SET team_id = $2 WHERE id = $1`, tk.ID, billing)
	mustExec(t, w.d, `DELETE FROM river_job WHERE args->>'workspace_id' = $1`, w.wid.String())
	_, err := w.d.Jobs.Insert(w.ctx, jobs.SendTicketEmailArgs{WorkspaceID: w.wid, TicketID: tk.ID, Subject: "How did we do?",
		HTML: `<p>Hi {{ contact.first_name | default: "there" }}, how did {{ team.name }} do?</p>{{ survey }}`, AutoGenerated: true, Template: true,
		SurveyURL: "http://app.test/csat/tok?score="}, nil)
	if err != nil {
		t.Fatal(err)
	}
	sent := w.sendQueued(t)
	if len(sent) != 1 {
		t.Fatalf("sent %d", len(sent))
	}
	env := sent[0]
	env.Text = strings.ReplaceAll(env.Text, "\r\n", "\n")
	if subj := env.GetHeader("Subject"); !strings.HasPrefix(subj, "How did we do? [#") {
		t.Errorf("subject %q", subj)
	}
	if !strings.Contains(env.HTML, "Hi Carla, how did Billing do?") || strings.Count(env.HTML, "http://app.test/csat/tok?score=") != 5 ||
		!strings.Contains(env.HTML, "2px solid #2563EB") {
		t.Errorf("html %s", env.HTML)
	}
	if !strings.Contains(env.Text, "1 (Very poor): http://app.test/csat/tok?score=1") || !strings.Contains(env.Text, "how did Billing do?") {
		t.Errorf("text %q", env.Text)
	}
}

func TestEmailTemplateRoutes(t *testing.T) {
	w := newWorld(t)
	srv := w.api(w.admin)
	base := srv.URL + "/v1/email-templates/" + w.brand.String()

	var got EmailTemplates
	if code := doJSON(t, "GET", base, nil, &got); code != 200 || !got.Layout.IsDefault || got.Layout.Options.History != "last" ||
		!strings.Contains(got.CSAT.BodyHTML, "{{ survey }}") {
		t.Fatalf("defaults %d %+v", code, got)
	}

	// Problems are refused with each one listed.
	var problem struct {
		Detail string
		Errors []struct {
			Message string
			Value   any
		}
	}
	code := doJSON(t, "PUT", base+"/csat", map[string]any{"body_html": "<p>{{ contact.nmae }}</p>"}, &problem)
	if code != 422 || len(problem.Errors) != 2 || problem.Errors[0].Value != "{{ contact.nmae }}" {
		t.Fatalf("csat problems %d %+v", code, problem)
	}
	code = doJSON(t, "PUT", base+"/layout", map[string]any{"options": map[string]any{"mode": "custom"}, "body_html": "<p>no slot</p>"}, &problem)
	if code != 422 || !strings.Contains(problem.Detail, "content") {
		t.Fatalf("layout problems %d %+v", code, problem)
	}

	// Saved, sanitized, published; reset goes back.
	var saved struct {
		BodyHTML  string `json:"body_html"`
		IsDefault bool   `json:"is_default"`
		Options   struct{ Style, Accent string }
	}
	code = doJSON(t, "PUT", base+"/layout", map[string]any{"options": map[string]any{"mode": "custom", "style": "branded", "accent": "#123456"},
		"body_html": `<div onclick="x()" style="color: {{ brand.color }}">{{ content }}</div><script>x</script>`}, &saved)
	if code != 200 || saved.IsDefault || saved.Options.Accent != "#123456" || strings.Contains(saved.BodyHTML, "onclick") ||
		strings.Contains(saved.BodyHTML, "script") || !strings.Contains(saved.BodyHTML, `style="color: {{ brand.color }}"`) {
		t.Fatalf("saved %d %+v", code, saved)
	}
	if w.eventCount("email_template.updated") != 1 {
		t.Fatal("no event")
	}
	if code := doJSON(t, "DELETE", base+"/layout", nil, nil); code != 204 {
		t.Fatalf("reset %d", code)
	}
	if code := doJSON(t, "GET", base, nil, &got); code != 200 || !got.Layout.IsDefault {
		t.Fatalf("after reset %+v", got)
	}

	// Another workspace's brand is not found; agents cannot save.
	if code := doJSON(t, "GET", srv.URL+"/v1/email-templates/"+ids.New().String(), nil, nil); code != 404 {
		t.Fatalf("foreign brand %d", code)
	}
	agent := *w.admin
	agent.Role = auth.RoleAgent
	asAgent := w.api(&agent)
	if code := doJSON(t, "PUT", asAgent.URL+"/v1/email-templates/"+w.brand.String()+"/csat", map[string]any{"subject": "x"}, nil); code != 403 {
		t.Fatalf("agent save %d", code)
	}

	// The variable list includes custom fields.
	mustExec(t, w.d, `INSERT INTO custom_fields (workspace_id, entity, key, name, type) VALUES ($1, 'contact', 'plan', 'Plan', 'text')`, w.wid)
	var cat TemplateCatalog
	if code := doJSON(t, "GET", srv.URL+"/v1/templates/variables", nil, &cat); code != 200 {
		t.Fatalf("variables %d", code)
	}
	found := false
	for _, v := range cat.Variables {
		found = found || (v.Key == "contact.fields.plan" && v.Label == "Plan")
	}
	if !found || len(cat.Slots) != 4 {
		t.Fatalf("catalog %+v", cat)
	}
}

func TestTemplatePreviewAndTest(t *testing.T) {
	w := newWorld(t)
	srv := w.api(w.admin)
	var p TemplatePreview
	code := doJSON(t, "POST", srv.URL+"/v1/templates/preview", map[string]any{"kind": "signature",
		"body_html": "<p>{{ agent.name }} at {{ team.name }} for {{ contact.first_name }} {{ contact.nmae }}</p>"}, &p)
	if code != 200 || !strings.Contains(p.HTML, "Anna Agent at Acme for Jane") || len(p.Problems) != 1 || !strings.HasPrefix(p.Subject, "Re: ") {
		t.Fatalf("signature preview %d %+v", code, p.Problems)
	}
	code = doJSON(t, "POST", srv.URL+"/v1/templates/preview", map[string]any{"kind": "csat"}, &p)
	if code != 200 || strings.Count(p.HTML, "/csat#t=preview&amp;score=") != 5 || len(p.Problems) != 0 {
		t.Fatalf("csat preview %d %+v", code, p.Problems)
	}
	code = doJSON(t, "POST", srv.URL+"/v1/templates/preview", map[string]any{"kind": "auto_reply", "subject": "Got it: {{ ticket.subject }}",
		"body_html": "<p>{{ agent.name | default: 'The team' }} will answer</p>"}, &p)
	if code != 200 || !strings.Contains(p.HTML, "The team will answer") || !strings.HasPrefix(p.Subject, "Got it: Can") {
		t.Fatalf("auto-reply preview %d %q %s", code, p.Subject, p.HTML)
	}
	if code := doJSON(t, "POST", srv.URL+"/v1/templates/preview", map[string]any{"kind": "reply", "ticket_id": ids.New().String()}, nil); code != 404 {
		t.Fatalf("unknown ticket %d", code)
	}

	rec := &recordingMailer{}
	prev := w.d.Mailer
	w.d.Mailer = rec
	defer func() { w.d.Mailer = prev }()
	if code := doJSON(t, "POST", srv.URL+"/v1/templates/test", map[string]any{"kind": "csat"}, nil); code != 200 {
		t.Fatalf("test send %d", code)
	}
	if len(rec.sent) != 1 || !strings.HasPrefix(rec.sent[0].Subject, "[Test] ") || !strings.HasPrefix(rec.sent[0].To, "anna-") {
		t.Fatalf("test mail %+v", rec.sent)
	}
}
