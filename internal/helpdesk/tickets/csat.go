// CSATTTL is how long a satisfaction link stays valid.
const CSATTTL = 30 * 24 * time.Hour

// requestCSAT sends the satisfaction survey when a ticket is solved and the workspace
// has CSAT enabled. The token is stored hashed; the email carries it once.
func requestCSAT(ctx context.Context, tx pgx.Tx, d *deps.Deps, wid, tid uuid.UUID) error {
	s, err := hd.LoadSettings(ctx, tx, wid)
	if err != nil || !s.CSATEnabled {
		return err
	}
	var email *string
	var score *int16
	var requested *time.Time
	var spam bool
	var brandID uuid.UUID
	err = tx.QueryRow(ctx, `SELECT c.email, t.csat_score, t.csat_requested_at, t.spam, t.brand_id
		FROM tickets t LEFT JOIN contacts c ON c.id = t.contact_id
		WHERE t.workspace_id = $1 AND t.id = $2`, wid, tid).Scan(&email, &score, &requested, &spam, &brandID)
	if err != nil {
		return err
	}
	// One survey per ticket a day; rated, spam and contactless tickets get none.
	if email == nil || *email == "" || score != nil || spam || (requested != nil && time.Since(*requested) < 24*time.Hour) {
		return nil
	}
	design, err := templates.LoadDesign(ctx, tx, wid, brandID)
	if err != nil {
		return err
	}
	token := crypto.RandomToken(32)
	if _, err := tx.Exec(ctx, `UPDATE tickets SET csat_token_hash = $3, csat_requested_at = now() WHERE workspace_id = $1 AND id = $2`,
		wid, tid, crypto.HashToken(token)); err != nil {
		return err
	}
	// The brand's survey email (contracts/templates.md), filled when it is sent.
	_, err = d.Jobs.InsertTx(ctx, tx, jobs.SendTicketEmailArgs{WorkspaceID: wid, TicketID: tid, Subject: design.CSATSubject,
		HTML: design.CSATHTML, AutoGenerated: true, Template: true, SurveyURL: CSATURL(d.Cfg.AppURL, token)},
		&river.InsertOpts{Queue: jobs.QueueEmail, MaxAttempts: 5})
	return err
}

// CSATURL is the survey link of a token, without its score. The token rides in the
// fragment, which browsers never send to a server, so no access log or analytics keeps it.
func CSATURL(appURL, token string) string {
	return strings.TrimRight(appURL, "/") + "/csat#t=" + token + "&score="
}

// CSATView is what the public survey page shows.
type CsatSurvey struct {
	WorkspaceName string `json:"workspace_name"`
	BrandColor    string `json:"brand_color"`
	Ticket        struct {
		Number  int64  `json:"number"`
		Subject string `json:"subject"`
	} `json:"ticket"`
	Score   *int   `json:"score"`
	Comment string `json:"comment"`
	Locale  string `json:"locale" doc:"Workspace default language (BCP 47), empty when not set"`
}

type csatRow struct {
	wid, tid uuid.UUID
	view     CsatSurvey
}

func loadCSAT(ctx context.Context, q db.Querier, token string, lock bool) (csatRow, error) {
	var r csatRow
	var score *int16
	var requested *time.Time
	var settings []byte
	if len(token) < 20 || len(token) > 100 {
		return r, httpx.NotFound("Survey")
	}
	sql := `SELECT t.workspace_id, t.id, t.number, t.subject, t.csat_score, t.csat_comment, t.csat_requested_at, w.name, w.settings
		FROM tickets t JOIN workspaces w ON w.id = t.workspace_id
		WHERE t.csat_token_hash = $1 AND t.deleted_at IS NULL`
	if lock {
		sql += ` FOR UPDATE OF t`
	}
	err := q.QueryRow(ctx, sql, crypto.HashToken(token)).Scan(&r.wid, &r.tid, &r.view.Ticket.Number, &r.view.Ticket.Subject,
		&score, &r.view.Comment, &requested, &r.view.WorkspaceName, &settings)
	if db.IsNotFound(err) || (err == nil && (requested == nil || time.Since(*requested) > CSATTTL)) {
		return r, httpx.NotFound("Survey")
	}
	if err != nil {
		return r, err
	}
	st := hd.ParseSettings(settings)
	r.view.BrandColor, r.view.Locale = st.BrandColor, st.Locale
	if score != nil {
		v := int(*score)
		r.view.Score = &v
	}
	return r, nil
}

type ipKey struct{}

// clientIPMiddleware puts the caller's address in the context for public rate limits.
func clientIPMiddleware(d *deps.Deps) func(huma.Context, func(huma.Context)) {
	ipOf := httpx.ClientIP(d.Cfg.TrustProxy, d.Cfg.ProxyHops)
	return func(ctx huma.Context, next func(huma.Context)) {
		r, _ := humachi.Unwrap(ctx)
		next(huma.WithValue(ctx, ipKey{}, ipOf(r)))
	}
}

func clientIP(ctx context.Context) string { s, _ := ctx.Value(ipKey{}).(string); return s }

func registerCSAT(d *deps.Deps, api huma.API) {
	mw := huma.Middlewares{clientIPMiddleware(d)}
	// The survey token rides in the body, never the URL, where proxies and logs keep it.
	huma.Register(api, huma.Operation{OperationID: "get-csat", Method: http.MethodPost, Path: "/v1/public/csat/survey",
		Summary: "Get a satisfaction survey", Tags: []string{"Public"}, Security: []map[string][]string{}, Middlewares: mw},
		func(ctx context.Context, in *struct {
			Body struct {
				Token string `json:"token" maxLength:"200"`
			}
		}) (*struct{ Body CsatSurvey }, error) {
			if !d.Limiter.Allow("csat:"+clientIP(ctx), 60, time.Minute) {
				return nil, httpx.RateLimited()
			}
			r, err := loadCSAT(ctx, d.DB.Pool, in.Body.Token, false)
			if err != nil {
				return nil, httpx.Wrap(err)
			}
			return &struct{ Body CsatSurvey }{r.view}, nil
		})

	type csatAnswerBody struct {
		Token   string `json:"token" maxLength:"200"`
		Score   int    `json:"score" minimum:"1" maximum:"5"`
		Comment string `json:"comment,omitempty" maxLength:"2000"`
	}
	huma.Register(api, huma.Operation{OperationID: "submit-csat", Method: http.MethodPost, Path: "/v1/public/csat/rating",
		Summary: "Answer a satisfaction survey", Tags: []string{"Public"}, Security: []map[string][]string{}, Middlewares: mw},
		func(ctx context.Context, in *struct {
			Body csatAnswerBody
		}) (*struct{ Body CsatSurvey }, error) {
			if !d.Limiter.Allow("csat:"+clientIP(ctx), 30, time.Minute) {
				return nil, httpx.RateLimited()
			}
			comment := strings.TrimSpace(hd.HTMLToText(in.Body.Comment))
			var out CsatSurvey
			err := d.DB.Tx(ctx, func(tx pgx.Tx) error {
				r, err := loadCSAT(ctx, tx, in.Body.Token, true)
				if err != nil {
					return err
				}
				if _, err := tx.Exec(ctx, `UPDATE tickets SET csat_score = $3, csat_comment = $4, updated_at = now()
					WHERE workspace_id = $1 AND id = $2`, r.wid, r.tid, in.Body.Score, comment); err != nil {
					return err
				}
				prev := r.view.Score
				if prev == nil || *prev != in.Body.Score || r.view.Comment != comment {
					data := map[string]any{"score": in.Body.Score}
					if comment != "" {
						data["comment"] = comment
					}
					if _, err := domain.LogActivity(ctx, tx, r.wid, r.tid, "contact", nil, "csat_received", data); err != nil {
						return err
					}
					if err := domain.PublishTicketUpdated(ctx, tx, r.wid, r.tid, []string{"csat"}); err != nil {
						return err
					}
				}
				out = r.view
				out.Score, out.Comment = &in.Body.Score, comment
				return nil
			})
			if err != nil {
				return nil, httpx.Wrap(err)
			}
			return &struct{ Body CsatSurvey }{out}, nil
		})
}
