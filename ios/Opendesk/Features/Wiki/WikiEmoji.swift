/// A group of the icon picker.
struct WikiEmojiGroup: Identifiable, Sendable {
    let id: String
    let title: String
    /// Each emoji with the English words people search it by.
    let emoji: [(String, String)]
}

/// Emoji a wiki page can wear as its icon (web `components/wiki/emoji.ts`, the same list,
/// so every one passes the server's check, contracts/wiki.md "Icons").
enum WikiEmoji {
    /// Emoji whose words all start with what was typed.
    static func search(_ query: String) -> [String] {
        let words = query.lowercased().split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return [] }
        var out: [String] = []
        for group in groups {
            for (emoji, names) in group.emoji {
                let parts = names.split(separator: " ")
                if words.allSatisfy({ word in parts.contains { $0.hasPrefix(word) } }) { out.append(emoji) }
            }
        }
        return out
    }

